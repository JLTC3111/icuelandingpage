import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import messages from '../src/i18n/messages.js'
import founderBiography from '../src/data/founderBiography.js'
import founderContent from '../src/data/founderContent.js'
import leadershipContent from '../src/data/leadershipContent.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const run = promisify(execFile)
const generatedMarker = '/* Landing subsets generated by scripts/optimize-assets.mjs. */'
const strings = (value) => typeof value === 'string' ? [value] : value && typeof value === 'object' ? Object.values(value).flatMap(strings) : []

async function staticText(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  return (await Promise.all(entries.map(async (entry) => {
    const filename = path.join(directory, entry.name)
    if (entry.isDirectory()) return staticText(filename)
    return /\.(jsx|css)$/.test(entry.name) && entry.name !== 'cjk-fonts.css' ? readFile(filename, 'utf8') : ''
  }))).join('\n')
}

export async function optimizeAssets() {
  const dataFile = path.join(root, 'src/data/siteContent.json')
  const data = JSON.parse(await readFile(dataFile, 'utf8'))
  const staticCopy = await staticText(path.join(root, 'src'))
  const languages = 'Tiếng Việt English Deutsch Français 한국어 日本語'
  const corpora = Object.fromEntries(['ja', 'ko'].map((locale) => [locale, [
    ...strings(data.locales[locale]), ...strings(data.contact), ...strings(messages[locale]),
    ...strings(founderBiography[locale]), ...strings(founderContent[locale]), ...strings(leadershipContent[locale]),
    staticCopy, languages, '0123456789/%+−↗→←↑↓·©–—…',
  ].join('\n')]))
  const cssBase = (await readFile(path.join(root, 'src/cjk-fonts.css'), 'utf8')).split(generatedMarker)[0].trim()
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'icue-assets-'))
  try {
    const input = path.join(temporary, 'input.json')
    const output = path.join(temporary, 'output.json')
    await writeFile(input, JSON.stringify({ root, data, corpora, cssBase, generatedMarker }))
    await run('python3', [path.join(root, 'scripts/optimize-assets.py'), input, output], { maxBuffer: 1024 * 1024 })
    const result = JSON.parse(await readFile(output, 'utf8'))
    await writeFile(dataFile, `${JSON.stringify(result.data, null, 2)}\n`)
    console.log(JSON.stringify(result.statistics, null, 2))
  } finally {
    await rm(temporary, { recursive: true, force: true })
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await optimizeAssets()
