import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import messages from '../src/i18n/messages.js'
import founderContent from '../src/data/founderContent.js'
import founderBiography, { nguoiDoThi, remembrance } from '../src/data/founderBiography.js'
import leadershipContent, { leadershipSources } from '../src/data/leadershipContent.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const content = JSON.parse(await readFile(path.join(root, 'src/data/siteContent.json'), 'utf8'))
const directory = path.join(root, 'src/data/locales')
await mkdir(directory, { recursive: true })
for (const locale of ['vi', 'en', 'de', 'fr', 'ko', 'ja']) {
  const pack = {
    locale, copy: messages[locale], content: content.locales[locale], contact: content.contact,
    founder: founderContent[locale], leadership: leadershipContent[locale], leadershipSources,
  }
  const reader = { ...founderBiography[locale], nguoiDoThi, remembrance }
  for (const [name, value] of [[locale, pack], [`${locale}-founder`, reader]]) {
    await writeFile(path.join(directory, `${name}.js`), `// Generated by scripts/generate-locales.mjs; edit the canonical content sources.\nexport default ${JSON.stringify(value)}\n`)
  }
}
console.log('Generated six independently loadable locale packs and founder readers.')
